function buildBitfield(progress: number, status: TorrentItem['status']): ChunkState[] {
  const cells: ChunkState[] = new Array(128).fill(0);
  const completedCount = Math.floor((progress / 100) * 128);

  for (let i = 0; i < 128; i++) {
    if (status === 'SEEDING' || status === 'ROUTED' || progress >= 100) {
      cells[i] = 3;
    } else if (i < completedCount) {
      cells[i] = 3;
    } else if (status === 'ERROR' && (i === completedCount || i === completedCount + 1)) {
      cells[i] = 2; // Verifying Hash / Mismatch zone
    } else if (status === 'DOWNLOADING' && i >= completedCount && i < completedCount + 6) {
      cells[i] = i % 2 === 0 ? 1 : 2;
    } else if (status === 'DOWNLOADING' && (i * 7) % 19 === 0 && i > completedCount) {
      cells[i] = 1; // Scattered out-of-order swarm chunks
    } else {
      cells[i] = 0;
    }
  }
  return cells;
}

